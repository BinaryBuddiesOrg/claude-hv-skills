#!/usr/bin/env python3
"""Generate REGISTRY.md from plugins/*/capabilities.json, skill frontmatter and agents.

Usage:  python3 tooling/build_registry.py           # rewrite REGISTRY.md
        python3 tooling/build_registry.py --check   # exit 1 if REGISTRY.md is stale

Deterministic: sorted rows, no timestamps — so --check is a pure text comparison and
newadder's gate never fails on a clock. REGISTRY.md is never edited by hand; the lint
fails on a missing marker or a stale file.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _lib as L  # noqa: E402

MARKER = "<!-- GENERATED by tooling/build_registry.py — do not edit; lint fails on manual edits -->"


def _cell(value) -> str:
    if value is None or value == "" or value == []:
        return "—"
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    return str(value).replace("|", "\\|").replace("\n", " ")


def _hardware(h: dict | None) -> str:
    if not h:
        return "—"
    gpu = h.get("gpu_vram_gb_min", 0) or 0
    return f"GPU ≥ {gpu} GB" if gpu else ("CPU" if h.get("cpu_ok", True) else "—")


def _tools(tools: list) -> str:
    names = []
    for t in tools or []:
        if isinstance(t, dict):
            names.append(t["name"] + ("" if t.get("required", True) else "?"))
        else:
            names.append(str(t))
    return _cell(names)


def collect() -> dict:
    skills, caps, agents = [], [], []
    counts = {"plugins": 0, "skills": 0, "capabilities": 0, "evals": 0}
    status_counts: dict[str, int] = {}
    for plugin in L.plugin_dirs():
        counts["plugins"] += 1
        cases = L.eval_cases(plugin)
        counts["evals"] += len(cases)
        evals_by_skill: dict[str, int] = {}
        for c in cases:
            evals_by_skill[c.parent.name] = evals_by_skill.get(c.parent.name, 0) + 1
        for skill in L.skill_dirs(plugin):
            counts["skills"] += 1
            md = skill / "SKILL.md"
            row = {"plugin": plugin.name, "skill": skill.name, "role": "?", "status": "?",
                   "capabilities": [], "tools": [], "evals": evals_by_skill.get(skill.name, 0)}
            if md.is_file():
                try:
                    fm, _ = L.read_frontmatter(md)
                    meta = fm.get("metadata") or {}
                    if isinstance(meta, dict):
                        row.update(role=meta.get("role", "?"), status=meta.get("status", "?"),
                                   capabilities=meta.get("capabilities", []) or [], tools=meta.get("tools", []) or [])
                except L.FrontmatterError:
                    row["status"] = "invalid frontmatter"
            skills.append(row)
        data = L.load_capabilities(plugin)
        for cap in (data or {}).get("capabilities", []):
            counts["capabilities"] += 1
            st = cap.get("status", "?")
            status_counts[st] = status_counts.get(st, 0) + 1
            caps.append({"id": cap.get("id"), "domain": plugin.name, "style": cap.get("style"),
                         "status": st, "skill": cap.get("skill"), "tools": cap.get("tools", []),
                         "hardware": cap.get("hardware"), "evals": cap.get("evals", [])})
        for agent in L.agent_files(plugin):
            try:
                fm, _ = L.read_frontmatter(agent)
                desc = str(fm.get("description", ""))
                if len(desc) > 160:
                    desc = desc[:160].rsplit(" ", 1)[0] + " …"
                agents.append({"plugin": plugin.name, "agent": fm.get("name", agent.stem), "description": desc})
            except L.FrontmatterError:
                agents.append({"plugin": plugin.name, "agent": agent.stem, "description": "(invalid frontmatter)"})
    skills.sort(key=lambda r: (r["plugin"], r["skill"]))
    caps.sort(key=lambda r: (r["domain"], r["id"] or ""))
    agents.sort(key=lambda r: (r["plugin"], r["agent"]))
    return {"skills": skills, "caps": caps, "agents": agents, "counts": counts, "status_counts": status_counts}


def render(data: dict) -> str:
    c, sc = data["counts"], data["status_counts"]
    order = ["stable", "tested", "draft", "planned", "idea", "deprecated"]
    status_line = " · ".join(f"{sc[s]} {s}" for s in order if sc.get(s)) or "none"
    out = [
        "# Registry", "", MARKER, "",
        f"{c['plugins']} plugins · {c['skills']} skills · {c['capabilities']} capabilities ({status_line}) · {c['evals']} eval cases",
        "", "Statuses are defined in CONVENTIONS.md § Status lifecycle. Auto mode selects `tested` and `stable` capabilities only.",
        "", "## Skills", "",
        "| Plugin | Skill | Role | Status | Capabilities | Tools | Evals |", "|---|---|---|---|---|---|---|",
    ]
    if data["skills"]:
        for r in data["skills"]:
            out.append(f"| {r['plugin']} | `{r['plugin']}:{r['skill']}` | {_cell(r['role'])} | {_cell(r['status'])} | "
                       f"{_cell(r['capabilities'])} | {_cell(r['tools'])} | {r['evals'] or '—'} |")
    else:
        out.append("| — | — | — | — | — | — | — |")
    out += ["", "## Capabilities", "",
            "| Id | Domain | Style | Status | Skill | Tools | Hardware | Evals |", "|---|---|---|---|---|---|---|---|"]
    if data["caps"]:
        for r in data["caps"]:
            out.append(f"| `{r['id']}` | {r['domain']} | {_cell(r['style'])} | {r['status']} | {_cell(r['skill'])} | "
                       f"{_tools(r['tools'])} | {_hardware(r['hardware'])} | {_cell(r['evals'])} |")
    else:
        out.append("| — | — | — | — | — | — | — | — |")
    out += ["", "## Agents", "", "| Plugin | Agent | Description |", "|---|---|---|"]
    if data["agents"]:
        for r in data["agents"]:
            out.append(f"| {r['plugin']} | `{r['plugin']}:{r['agent']}` | {_cell(r['description'])} |")
    else:
        out.append("| — | — | — |")
    return "\n".join(out) + "\n"


def generate() -> str:
    return render(collect())


def check() -> bool:
    return L.REGISTRY.is_file() and L.REGISTRY.read_text(encoding="utf-8") == generate()


def main(argv: list[str]) -> int:
    if "--check" in argv:
        if check():
            print("REGISTRY.md is up to date")
            return 0
        print("REGISTRY.md is stale; run python3 tooling/build_registry.py", file=sys.stderr)
        return 1
    L.REGISTRY.write_text(generate(), encoding="utf-8")
    print(f"wrote {L.rel(L.REGISTRY)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
